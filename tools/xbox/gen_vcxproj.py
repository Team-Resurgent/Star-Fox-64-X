#!/usr/bin/env python3
r"""Write Star-Fox-64-X.sln / .vcxproj / .vcxproj.filters from rxdk.project.json.

The manifest is the authority (tools/xbox/gen_manifest.py writes it from the
Dreamcast Makefile); the Visual Studio project is RXDK's own rendering of it,
from `Rxdk.Cli generate-vcxproj` -- the RXDK platform toolset with its
property pages, so Build compiles with the same command lines as the CLI and
F5 is the Xbox Debugger (RXDK). Added to what the CLI writes:

  - a fixed project GUID (the CLI makes a new one each run, which would make
    every regeneration a change to the .sln and .vcxproj);
  - the Xbox Deployment page's properties (RxdkDeployPaths, RxdkForceCopy,
    RxdkCreateIso) from the manifest: the CLI writes deployPaths as ISO items
    only and drops forceCopy, so Deploy / F5 would copy no game data;
  - StageIsoFiles redefined to keep data\sf_data\ as a folder in the ISO
    (RXDK's copies every deploy file into the ISO's root);
  - a .vcxproj.filters, so Solution Explorer shows the source tree's folders.

    python tools/xbox/gen_vcxproj.py
"""
import json
import os
import re
import shutil
import subprocess
import sys
import tempfile
import uuid
from xml.sax.saxutils import escape

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import xbconfig  # noqa: E402

ROOT = xbconfig.ROOT
NAME = "Star-Fox-64-X"
GUID = "{%s}" % str(uuid.uuid5(uuid.NAMESPACE_URL, "https://github.com/jnmartin84/sf64-dc#xbox")).upper()
FILTER_NS = uuid.uuid5(uuid.NAMESPACE_URL, "https://github.com/jnmartin84/sf64-dc#xbox-filters")

HEADER = """<!--
  Generated by tools/xbox/gen_vcxproj.py from rxdk.project.json (which
  tools/xbox/gen_manifest.py writes from the Dreamcast Makefile). Run
  setup.py once first: it builds the assets from your ROM into data/ and
  Platform/xbox/gen/. Then Build here; F5 is the Xbox Debugger (RXDK).
-->
"""


def write_if_changed(path, text):
    old = None
    if os.path.isfile(path):
        with open(path, encoding="utf-8-sig", newline="") as f:
            old = f.read()
    if old != text:
        with open(path, "w", encoding="utf-8", newline="") as f:
            f.write(text)


def main():
    cli = xbconfig.rxdk_cli()
    tmp = tempfile.mkdtemp(prefix="sf64x_vcx_")
    try:
        shutil.copy(os.path.join(ROOT, "rxdk.project.json"), tmp)
        r = subprocess.run([cli, "generate-vcxproj", "--project-root", tmp],
                           capture_output=True, text=True)
        sys.stdout.write(r.stdout)
        sys.stderr.write(r.stderr)
        if r.returncode != 0:
            raise SystemExit("gen_vcxproj: Rxdk.Cli generate-vcxproj failed (%d)" % r.returncode)
        with open(os.path.join(tmp, NAME + ".vcxproj"), encoding="utf-8-sig") as f:
            proj = f.read()
        with open(os.path.join(tmp, NAME + ".sln"), encoding="utf-8-sig") as f:
            sln = f.read()
    finally:
        shutil.rmtree(tmp, ignore_errors=True)

    m = re.search(r"<ProjectGuid>(\{[0-9A-Fa-f-]+\})</ProjectGuid>", proj)
    if not m:
        raise SystemExit("gen_vcxproj: no ProjectGuid in the generated project")
    proj = proj.replace(m.group(1), GUID)
    sln = sln.replace(m.group(1), GUID).replace(m.group(1).upper(), GUID)
    proj = proj.replace('<?xml version="1.0" encoding="utf-8"?>\n',
                        '<?xml version="1.0" encoding="utf-8"?>\n' + HEADER, 1)

    # The media: the CLI writes the manifest's deployPaths as IsoCopyDir items
    # only, so Deploy / F5 (which reads RxdkDeployPaths) would copy none of
    # it. Set the Xbox Deployment page's properties instead; RXDK's props
    # turn RxdkDeployPaths into the IsoCopyDir items itself.
    with open(os.path.join(ROOT, "rxdk.project.json"), encoding="utf-8") as f:
        manifest = json.load(f)
    cfg = manifest["configurations"]["Release"]
    deploy = cfg.get("deployPaths", [])
    iso_items = "".join('    <IsoCopyDir Include="%s" />\n' % escape(p.replace("/", "\\"))
                        for p in deploy)
    old = "  <ItemGroup>\n" + iso_items + "  </ItemGroup>\n"
    if deploy and old not in proj:
        raise SystemExit("gen_vcxproj: the generated project's IsoCopyDir items are not as expected")
    props = ("  <PropertyGroup>\n"
             "    <RxdkDeployPaths>%s</RxdkDeployPaths>\n"
             "    <RxdkForceCopy>%s</RxdkForceCopy>\n"
             "    <RxdkCreateIso>%s</RxdkCreateIso>\n"
             "  </PropertyGroup>\n"
             % (escape(";".join(p.replace("/", "\\") for p in deploy)),
                "true" if cfg.get("forceCopy") else "false",
                "false" if cfg.get("createIso") is False else "true"))
    # RXDK's props also add a default IsoCopyDir "Media"; this project's
    # Media/ is the upstream README's screenshots, not title media.
    props += ("  <ItemGroup>\n"
              "    <IsoCopyDir Remove=\"Media\" />\n"
              "  </ItemGroup>\n")
    proj = proj.replace(old, props, 1) if deploy else proj.replace(
        '  <Import Project="$(VCTargetsPath)\\Microsoft.Cpp.targets" />',
        props + '  <Import Project="$(VCTargetsPath)\\Microsoft.Cpp.targets" />', 1)

    # RXDK's StageIsoFiles copies every file under a deploy folder straight
    # into the ISO's root (one Copy to DestinationFolder), where Rxdk.Cli and
    # Deploy keep the folder: the game opens D:\data\sf_data\*.bin. The same
    # target, redefined after RXDK's (the later definition wins), keeping the
    # tree.
    stage = r"""  <!-- gen_vcxproj.py: RXDK's StageIsoFiles, keeping each deploy folder's tree in the ISO
       (data\sf_data\x.bin at data\sf_data\x.bin, as Rxdk.Cli and Deploy place it, not at the
       root). Otherwise the same target. -->
  <Target Name="StageIsoFiles"
          Inputs="%(ImageBld.OutputFile);@(IsoCopy);@(IsoCopyDir)"
          Outputs="@(Xiso)"
          Condition="'@(Xiso)' != ''"
          DependsOnTargets="RxdkBuildResources">
    <ItemGroup>
      <_IsoTreeFile Include="%(IsoCopyDir.Identity)\**" Condition="'@(IsoCopyDir)' != ''">
        <IsoDir>%(IsoCopyDir.Identity)</IsoDir>
      </_IsoTreeFile>
    </ItemGroup>
    <PropertyGroup>
      <_XisoDir>@(Xiso)</_XisoDir>
    </PropertyGroup>
    <RemoveDir Directories="$(_XisoDir)" />
    <Copy SourceFiles="%(ImageBld.OutputFile)"
          DestinationFiles="$(_XisoDir)\default.xbe"
          UseHardlinksIfPossible="true" />
    <Copy SourceFiles="@(IsoCopy)"
          DestinationFolder="$(_XisoDir)"
          UseHardlinksIfPossible="true" />
    <Copy SourceFiles="@(_IsoTreeFile)"
          DestinationFiles="@(_IsoTreeFile->'$(_XisoDir)\%(IsoDir)\%(RecursiveDir)%(Filename)%(Extension)')"
          UseHardlinksIfPossible="true" />
  </Target>
"""
    proj = proj.replace("</Project>", stage + "</Project>", 1)

    # .filters: one filter per source folder, plus the resources
    files = re.findall(r'<(ClCompile|RxdkResource) Include="([^"]+)"', proj)
    folders = set()
    for _, path in files:
        d = os.path.dirname(path)
        while d:
            folders.add(d)
            d = os.path.dirname(d)
    out = ['<?xml version="1.0" encoding="utf-8"?>',
           '<Project ToolsVersion="4.0" xmlns="http://schemas.microsoft.com/developer/msbuild/2003">',
           '  <ItemGroup>']
    for d in sorted(folders):
        out.append('    <Filter Include="%s">' % escape(d))
        out.append('      <UniqueIdentifier>{%s}</UniqueIdentifier>'
                   % str(uuid.uuid5(FILTER_NS, d.lower())).upper())
        out.append('    </Filter>')
    out.append('  </ItemGroup>')
    for kind in ("ClCompile", "RxdkResource"):
        out.append('  <ItemGroup>')
        for k, path in files:
            if k != kind:
                continue
            d = os.path.dirname(path)
            if d:
                out.append('    <%s Include="%s">' % (kind, escape(path)))
                out.append('      <Filter>%s</Filter>' % escape(d))
                out.append('    </%s>' % kind)
            else:
                out.append('    <%s Include="%s" />' % (kind, escape(path)))
        out.append('  </ItemGroup>')
    out.append('</Project>')
    filters = "\r\n".join(out) + "\r\n"

    proj = proj.replace("\r\n", "\n").replace("\n", "\r\n")
    sln = sln.replace("\r\n", "\n").replace("\n", "\r\n")
    write_if_changed(os.path.join(ROOT, NAME + ".vcxproj"), proj)
    write_if_changed(os.path.join(ROOT, NAME + ".vcxproj.filters"), filters)
    write_if_changed(os.path.join(ROOT, NAME + ".sln"), sln)
    print("gen_vcxproj: %s.sln, .vcxproj, .vcxproj.filters (%d files, %d folders)"
          % (NAME, len(files), len(folders)))


if __name__ == "__main__":
    main()
